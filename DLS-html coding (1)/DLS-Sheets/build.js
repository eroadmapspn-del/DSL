// Netlify build step (optional).
// If the environment variable DLS_API_URL is set, config.js is regenerated with it,
// so you never have to edit config.js by hand. Otherwise config.js is left untouched.
const fs = require('fs');
const url = (process.env.DLS_API_URL || '').trim();
if (!url) {
  console.log('[build] DLS_API_URL not set - leaving config.js as it is.');
  process.exit(0);
}
if (!/^https:\/\/script\.google\.com\/macros\/s\/[^/]+\/exec$/.test(url)) {
  console.error('[build] DLS_API_URL does not look like an Apps Script web-app URL (…/exec): ' + url);
  process.exit(1);
}
const poll = Number(process.env.DLS_POLL_MS) || 12000;
fs.writeFileSync('config.js',
  '// Generated by build.js from the DLS_API_URL environment variable\n' +
  'window.DLS_API_URL = ' + JSON.stringify(url) + ';\n' +
  'window.DLS_POLL_MS = ' + poll + ';\n');
console.log('[build] config.js written.');
